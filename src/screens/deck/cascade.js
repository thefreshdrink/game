// Экран 2, вход веера: карты падают с неба, отскакивают и садятся в свои
// слоты. Вынесено из deck.js (задача 5 бэклога агента) без изменения
// поведения — физика и значения перенесены как были.

import { easeInOutQuad, clamp01 } from '../../core/ease.js';
import { cardCenterAt } from './fan.js';

// Вход карт на экран колоды. История: (1) карта подпрыгивала на месте вдоль
// своего угла — читалось как подскок; (2) все стартовали из одной точки и
// разворачивались веером одним easeOutBack — «раздача из стопки»; (3) мок
// «Тасовка колоды» 2026-09-11 — карты вылетали из разных точек в разные
// стороны, отскакивали дугами, за ними тянулся призрачный след — на 20
// полноразмерных картах суматошно; (4) правка в чате: карты ПАДАЮТ С НЕБА
// каждая примерно над своим местом в вере, без броска в стороны; (5) правка
// в чате: совсем без дуги — плоско, вернули лёгкую дугу (широкий разброс
// точки старта + снос к своей X); (6) правка в чате: скорость сделали
// «плавнее и медленнее» — не понравилось, мешало, откат на прежнюю
// скорость; (7) правка в чате: тоже отменён следом — след («шлейф»)
// читался грязью, а не «тасовкой». Итог: дуга есть, следа нет, скорость —
// как в (5)/(4).
//
// Карты стартуют СРАЗУ, как погасла старая реплика (CARDS_START), пока
// экран ещё пуст — заголовок и подпись ждут не фиксированное время, а
// firstPlaceT (см. физику ниже): момент, когда ПЕРВАЯ карта на третьем
// отскоке начала уходить в свой слот. До этого момента на экране нет
// текста вообще (правка в чате: «до этого никакого текста на экране»).
//
// Раскладка веера (layoutCards, cardCenterAt), ховер, волна-подсказка,
// вылет выбранной карты — БЕЗ изменений: меняется только вход.
export const CASCADE_STAGGER = 0.06;    // запуск карт друг за другом, сек
const CASCADE_MAX_BOUNCES = 3;   // третий контакт с полом = уход в веер
const CASCADE_FLOOR_FRAC = 0.9;  // «пол» для отскока — доля высоты экрана (карта уходит низом за кадр, это ок)
const CASCADE_GRAV_FRAC = 2.6;   // гравитация = h * этого
const PLACE_DUR = 0.62;          // длительность финального отскока в слот, сек
const PLACE_ARC_FRAC = 0.16;     // высота горба этого отскока над прямой к слоту — доля высоты

// Детерминированный псевдослучай [0..1) по паре целых — тот же приём, что в
// моке «Тасовка колоды»: каскад раскладывается ОДИНАКОВО каждый заход, без
// генератора состояния. Служит только для разброса стартовых точек и
// траекторий отскока.
function pseudoRnd(i, s) {
  const x = Math.sin(i * 127.1 + s * 311.7) * 43758.5453;
  return x - Math.floor(x);
}

// Лёгкий перелёт с притормаживанием в конце — «приземление» карты.
function easeOutBack(x) {
  const c1 = 1.70158;
  const c3 = c1 + 1;
  return 1 + c3 * Math.pow(x - 1, 3) + c1 * Math.pow(x - 1, 2);
}

// ── ВХОД: карты падают с неба. Каждая карта появляется НАД кадром на
// разной высоте, с широким разбросом точки старта по X, и летит
// лёгкой ДУГОЙ (постоянный снос к своей цели + гравитация по Y —
// кривая, не прямая линия), отскакивает от нижней кромки, и на
// третьем контакте с полом уходит одной плавной дугой в свой слот.
// Без следа — пробовали короткий тусклый шлейф, правка в чате: читался
// грязью, а не тасовкой, убран совсем. Скорость — исходная, «плавнее
// и медленнее» пробовали и откатили тем же чатом: мешало. Шаг физики
// привязан к dt кадра (cascadePrevT), значения — доли высоты, поэтому
// падение одинаково на любом вьюпорте. Рисуем строго по индексу
// (карта правее — «спереди»).
//
// Шаг физики по картам, ещё не севшим в веер. onPlace(t) вызывается,
// когда карта уходит в финальный отскок (вызывающий сам решает, первая ли).
// dt — уже обрезанный шаг кадра.
export function stepCascade(cards, pivot, { t, dt, w, h, onPlace }) {
  const floorY = h * CASCADE_FLOOR_FRAC;
  const grav = h * CASCADE_GRAV_FRAC;

  // 1) Шаг физики (по картам, ещё не севшим в веер).
  cards.forEach((c, i) => {
    if (t < c.delay || c.placed) return;

    if (c.cx === undefined) {
      const home = cardCenterAt(pivot, c.angle, c.radius);
      // Появляется над кадром на разной высоте, с широким разбросом по
      // X (не строго над своим слотом) — постоянный снос к цели плюс
      // ускоряющееся падение по Y дают видимую дугу, а не прямую линию.
      c.cx = home.x + (pseudoRnd(i, 1) - 0.5) * w * 0.5;
      c.cy = -c.h * (0.35 + pseudoRnd(i, 5) * 0.6);
      c.vx = (home.x - c.cx) * 0.8;
      c.vy = h * (0.03 + pseudoRnd(i, 2) * 0.05);
      c.bounces = 0;
      c.placing = false;
      c.placeT = 0;
    }

    if (c.placing) {
      const pp = clamp01((t - c.placeT) / PLACE_DUR);
      const home = cardCenterAt(pivot, c.angle, c.radius);
      c.cx = c.px + (home.x - c.px) * easeInOutQuad(pp);
      c.cy = c.py + (home.y - c.py) * easeOutBack(pp)
        - PLACE_ARC_FRAC * h * 4 * pp * (1 - pp);
      if (pp >= 1) c.placed = true;
    } else {
      c.vy += grav * dt;
      c.cx += c.vx * dt;
      c.cy += c.vy * dt;
      const halfW = c.w / 2;
      if (c.cx < halfW) { c.cx = halfW; c.vx = Math.abs(c.vx) * 0.5; }
      if (c.cx > w - halfW) { c.cx = w - halfW; c.vx = -Math.abs(c.vx) * 0.5; }
      if (c.cy >= floorY) {
        c.cy = floorY;
        c.bounces += 1;
        if (c.bounces >= CASCADE_MAX_BOUNCES) {
          c.placing = true; c.placeT = t; c.px = c.cx; c.py = c.cy;
          // Заголовок/подпись в deck.js ждут первого такого момента.
          onPlace(t);
        } else {
          // Отскок почти вертикальный, каждый следующий слабее.
          const e = c.bounces === 1 ? 0.5 : 0.28;
          c.vy = -Math.abs(c.vy) * e;
          c.vx *= 0.6;
        }
      }
    }
  });
}

/** Угол карты на финальном отскоке — доворот из 0 в свой угол. */
export function placingAngle(c, t) {
  const pp = clamp01((t - c.placeT) / PLACE_DUR);
  return c.angle * easeInOutQuad(pp);
}
